-- 0040: screenshots (run_id, created_at) WHERE verdict IN ('new', 'unresolved').
--
-- A pending step (spec 2026-10-14-review-loop §3.1) has verdict `new` or
-- `unresolved`; a `passed` or undiffed one never is. The review queue
-- (`review.next`), the runs list's `pending` filter and the per-run pending
-- counts read a run's steps in capture order, restricted to those verdicts.
-- This partial index holds only those steps, so a run's candidates are found
-- without walking its passed steps. (A decided step keeps its verdict and is
-- still in the index: whether it has an active decision is read from
-- `checkpoint_decisions`.)
--
-- Additive and idempotent: re-applying this file is a no-op.
CREATE INDEX IF NOT EXISTS "screenshots_pending_idx" ON "screenshots" USING btree ("run_id","created_at") WHERE "screenshots"."verdict" IN ('new', 'unresolved');
